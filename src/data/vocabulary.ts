function toId(index: number): string {
  return `w${index.toString().padStart(4, "0")}`;
}

export const VOCABULARY: DictionaryEntry[] = ROWS.map((row, index) => {
  const [word, reading, type, level, meanings, alt] = row;
  return {
    id: toId(index),
    word,
    reading,
    type,
    level,
    meanings: meanings.split(";").map((m) => m.trim()).filter(Boolean),
    ...(alt ? { alt } : {}),
  };
});

export const VOCABULARY_BY_ID: ReadonlyMap<string, DictionaryEntry> = new Map(
  VOCABULARY.map((entry) => [entry.id, entry]),
);
